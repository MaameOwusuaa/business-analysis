def _inline(text: str) -> str:
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", text)
    text = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<i>\1</i>", text)
    text = re.sub(r"(?<!\w)_(.+?)_(?!\w)", r"<i>\1</i>", text)
    text = re.sub(r"`([^`]+)`", r"<font face='Courier'>\1</font>", text)
    return text


def markdown_flowables(md: str) -> list:
    out = []
    for line in md.splitlines():
        s = line.strip()
        if not s:
            continue
        if s.startswith("#"):
            out.append(Paragraph(_inline(s.lstrip("#").strip()), H3))
        elif s.startswith(("- ", "* ")):
            out.append(Paragraph(_inline(s[2:]), BULLET, bulletText="•"))
        elif re.match(r"^\d+\.\s", s):
            n, rest = s.split(".", 1)
            out.append(Paragraph(_inline(rest.strip()), BULLET, bulletText=f"{n}."))
        else:
            out.append(Paragraph(_inline(s), BODY))
    return out


def _table(rows: list[list], col_widths=None, header=True, font=7.8) -> Table:
    t = Table(rows, colWidths=col_widths, hAlign="LEFT", repeatRows=1 if header else 0)
    style = [
        ("FONTSIZE", (0, 0), (-1, -1), font), ("TEXTCOLOR", (0, 0), (-1, -1), colors.HexColor(TEXT_PRIMARY)),
        ("LINEBELOW", (0, 0), (-1, -1), 0.25, colors.HexColor("#e4e3df")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"), ("TOPPADDING", (0, 0), (-1, -1), 2.5), ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5),
    ]
    if header:
        style += [("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"), ("TEXTCOLOR", (0, 0), (-1, 0), colors.HexColor(TEXT_SECONDARY)),
                  ("LINEBELOW", (0, 0), (-1, 0), 0.8, colors.HexColor(TEXT_SECONDARY))]
    t.setStyle(TableStyle(style))
    return t


def _kpi_tiles(items: list[tuple[str, str]]) -> Table:
    cells = [[Paragraph(f"<font size=12.5><b>{v}</b></font><br/><font size=7.5 color='{TEXT_SECONDARY}'>{k}</font>", BODY)
              for k, v in items]]
    t = Table(cells, colWidths=[180 * mm / len(items)] * len(items), hAlign="LEFT")
    t.setStyle(TableStyle([("BOX", (0, 0), (-1, -1), 0.4, colors.HexColor("#e4e3df")),
                           ("INNERGRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#e4e3df")),
                           ("TOPPADDING", (0, 0), (-1, -1), 7), ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
                           ("LEFTPADDING", (0, 0), (-1, -1), 8)]))
    return t


def _ai_block(title: str, output: dict | None) -> list:
    if not output or not output.get("output_text"):
        return [Paragraph(title, H2), Paragraph("Not generated yet.", SMALL)]
    status = output.get("status", "needs_review")
    badge = (f"<font color='{VERIFY_COLORS.get(status, TEXT_SECONDARY)}'><b>&#9679;</b></font> "
             f"AI-generated by the Snwolley agent ({output.get('provider')}) &#183; {VERIFY_LABELS.get(status, status)}")
    v = output.get("validation") or {}
    if v.get("unsupported_numbers"):
        badge += f" &#183; unmatched: {', '.join(v['unsupported_numbers'][:6])}"
    return [Paragraph(title, H2), Paragraph(badge, SMALL), Spacer(1, 3)] + markdown_flowables(output["output_text"])


def _img(path: Path, width_mm: float) -> Image:
    img = Image(str(path))
    ratio = img.imageHeight / img.imageWidth
    img.drawWidth = width_mm * mm
    img.drawHeight = width_mm * mm * ratio
    return img


def _side_by_side(a: Path, b: Path) -> Table:
    t = Table([[_img(a, 88), _img(b, 88)]], colWidths=[90 * mm, 90 * mm], hAlign="LEFT")
    t.setStyle(TableStyle([("LEFTPADDING", (0, 0), (-1, -1), 0), ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    return t


def build_report(workspace_id: int, run_id: int, author: str, generate_missing_ai: bool = True,
                 user_id: int | None = None) -> Path:
    t0 = time.time()
    run = get_run(run_id, workspace_id)
    if not run:
        raise ValueError("Model run not found in this workspace.")
    ds = get_dataset(run["dataset_id"], workspace_id)
    ws = get_workspace(workspace_id)
    telco = ds["source"] == "synthetic_telco"
    d, m = run["details"], run["metrics"]
    is_clf = run["task_type"] == "classification"

    ai = {}
    tasks = ["executive_summary", "retention_actions"] if is_clf else ["executive_summary", "model_explainer"]
    for task in tasks:
        out = latest_output(workspace_id, task, run_id)
        if out is None and generate_missing_ai:
            run_task(task, workspace_id, run_id=run_id, dataset_id=ds["id"], user_id=user_id)
            out = latest_output(workspace_id, task, run_id)
        ai[task] = out

    settings = get_settings()
    out_dir = settings.storage_dir / f"ws_{workspace_id}" / "reports" / datetime.now().strftime("%Y%m%d_%H%M%S")
    out_dir.mkdir(parents=True, exist_ok=True)
    story: list = []
    title = f"{ws['name']}: {d.get('use_case_name', run['use_case_id'])}"
    as_of = to_date(ds["as_of_date"]) if telco else None
    story += [Paragraph(title, H1),
              Paragraph(f"Insight report &#183; data as of {as_of or 'upload'} &#183; prepared {datetime.now():%d %B %Y} "
                        f"&#183; {author}", SUB)]

    # ------------------------------------------------------------- KPIs
    if telco:
        res = run_analysis(workspace_id, as_of)
        k = res["kpi_summary"].data.iloc[0]
        ss = d.get("scoring_summary", {})
        story.append(_kpi_tiles([
            ("Active customers", f"{int(k['active_customers']):,}"),
            ("Monthly recurring revenue", f"GHS {float(k['mrr_ghs']):,.0f}"),
            ("90-day churn rate", f"{float(k['churn_rate_90d_pct']):.2f}%"),
            ("Expected leavers, next 90 days", f"{ss.get('expected_positives', 0):,.0f}"),
            (f"Revenue at risk ({ss.get('value_months', 12)} months)", f"GHS {ss.get('expected_value_at_risk_ghs', 0):,.0f}"),
        ]))
    story += _ai_block("Executive summary", ai.get("executive_summary"))

    # ------------------------------------------------------------- analysis
    if telco:
        story.append(PageBreak())
        story.append(Paragraph("What the data shows", H2))
        story.append(Paragraph("All figures below come from SQL run on the cleaned data layer. 90-day rates follow "
                               "customers active at the last fully observed snapshot "
                               f"({d.get('test_snapshot')}) for 90 days.", SMALL))
        story.append(_img(charts.churn_trend(res["monthly_churn_trend"].data, out_dir / "trend.png"), 180))
        con = res["churn_by_contract_plan"].data.copy()
        con["segment"] = con["contract_type"] + " / " + con["plan_type"]
        shift = [r for r in _region_shift(res["monthly_churn_by_region"].data) if r["region"] != "Unknown"]
        story.append(_side_by_side(
            charts.region_vs_rest(res["monthly_churn_by_region"].data, shift[0]["region"], out_dir / "regions.png"),
            charts.hbar(con.head(8), "segment", "churn_rate_90d_pct", "90-day churn by contract / plan", out_dir / "contract.png", fmt="{:.1f}")))
        u = res["usage_decline_early_warning"].data
        u = u[~u["usage_trend"].str.startswith("9")].copy()
        u["usage_trend"] = u["usage_trend"].str.replace(r"^\d+\.\s*", "", regex=True) + " (n=" + u["customers"].map("{:,}".format) + ")"
        p = res["payment_behaviour_vs_churn"].data.copy()
        p["payment_profile"] = p["payment_profile"].str.replace(r"^\d+\.\s*", "", regex=True) + " (n=" + p["customers"].map("{:,}".format) + ")"
        story.append(_side_by_side(
            charts.hbar(u, "usage_trend", "churn_rate_90d_pct", "90-day churn by data-use trend", out_dir / "usage.png", color=SERIES[2]),
            charts.hbar(p, "payment_profile", "churn_rate_90d_pct", "90-day churn by payment behaviour", out_dir / "pay.png", color=SERIES[2])))
        reasons = res["cancel_reasons"].data
        story.append(Paragraph("Recorded cancellation reasons (last 12 months)", H3))
        story.append(_table([["Reason", "Cancellations", "Share", "Lost monthly revenue"]] +
                            [[r.cancel_reason, f"{int(r.cancellations):,}", f"{r.share_pct:.1f}%", f"GHS {r.lost_mrr_ghs:,.0f}"]
                             for r in reasons.itertuples()], [60 * mm, 30 * mm, 25 * mm, 40 * mm]))

    # ------------------------------------------------------------- model
    story.append(PageBreak())
    story.append(Paragraph("The predictive model", H2))
    if is_clf:
        story.append(Paragraph(
            f"Outcome predicted: <b>{d.get('use_case_name')}</b>. Trained on {d.get('rows_train'):,} historical snapshots "
            f"({', '.join(d.get('train_snapshots') or [])}) and tested on {d.get('rows_test'):,} customers at "
            f"{d.get('test_snapshot')} ({d.get('validation')} validation, so the test mimics real future use). "
            f"Selected model: <b>{run['best_model']}</b> (highest PR-AUC).", BODY))
        rows = [["Model", "ROC-AUC", "PR-AUC", f"Reach @ top {100 * m['top_pct']:.0f}%", "Lift", "Brier"]]
        for r in d["comparison"]:
            rows.append([r["model"], f"{r['roc_auc']:.3f}", f"{r['pr_auc']:.3f}", f"{100 * r['recall_at_top']:.1f}%",
                         f"{r['lift_at_top']:.2f}x", f"{r['brier']:.4f}"])
        story.append(Spacer(1, 4))
        story.append(_table(rows, [55 * mm, 22 * mm, 22 * mm, 30 * mm, 18 * mm, 22 * mm]))
        story.append(_side_by_side(charts.capture_curve(d["lift_table"], out_dir / "capture.png"),
                                   charts.tiers(d["scoring_summary"]["tiers"], out_dir / "tiers.png")))
    else:
        rows = [["Model", "RMSE", "MAE", "R²"]] + [[r["model"], f"{r['rmse']:.2f}", f"{r['mae']:.2f}", f"{r['r2']:.3f}"] for r in d["comparison"]]
        story.append(_table(rows))
    story.append(_img(charts.drivers(d["drivers"], out_dir / "drivers.png"), 180))
    story.append(Paragraph("Drivers are measured by how much test performance drops when a feature is shuffled. "
                           "They show what the model relies on, not proven causes.", SMALL))

    if is_clf and d.get("campaign_simulation"):
        c = d["campaign_simulation"]
        a = c["assumptions"]
        story.append(Paragraph("Value of acting on the model (simulated on the test month)", H3))
        story.append(_table([
            ["", "Model-targeted", "Random selection"],
            ["Customers contacted", f"{c['contacted']:,}", f"{c['contacted']:,}"],
            ["Would-be churners reached", f"{c['positives_reached_model']:,}", f"{c['positives_reached_random']:,.0f}"],
            ["Customers saved (at assumed save rate)", f"{c['customers_saved_model']:,.0f}", f"{c['customers_saved_random']:,.0f}"],
            ["Revenue protected", f"GHS {c['revenue_protected_model_ghs']:,.0f}", f"GHS {c['revenue_protected_random_ghs']:,.0f}"],
            ["Net benefit after campaign cost", f"GHS {c['net_benefit_model_ghs']:,.0f}", f"GHS {c['net_benefit_random_ghs']:,.0f}"],
        ], [70 * mm, 40 * mm, 40 * mm]))
        story.append(Paragraph(
            f"Assumptions: contact top {100 * a['target_top_pct']:.0f}% of customers; contact cost GHS {a['contact_cost_ghs']}; "
            f"incentive GHS {a['offer_cost_ghs']} per saved customer; save rate {100 * a['save_rate']:.0f}%; "
            f"revenue valued over {a['value_months']} months. Change these in the use-case configuration.", SMALL))

    if telco and is_clf:
        q = load_named_queries("model_insights.sql")
        seg = run_query(q["risk_by_segment"].sql, {"ws": workspace_id, "run_id": run_id})
        story.append(KeepTogether([Paragraph("Where the predicted risk sits", H3), _table(
            [["Contract", "Plan", "Customers", "High risk", "Avg risk", "Revenue at risk / month"]] +
            [[r.contract_type, r.plan_type, f"{int(r.customers):,}", f"{int(r.high_risk_customers):,}",
              f"{r.avg_predicted_risk_pct:.1f}%", f"GHS {r.expected_monthly_revenue_at_risk_ghs:,.0f}"] for r in seg.itertuples()],
            [32 * mm, 24 * mm, 24 * mm, 22 * mm, 22 * mm, 42 * mm])]))

    # ------------------------------------------------------------- actions
    story.append(Spacer(1, 6))
    second = "retention_actions" if is_clf else "model_explainer"
    story += _ai_block("Recommended actions" if is_clf else "Model explanation", ai.get(second))

    # ------------------------------------------------------------- data quality + method
    if telco:
        dq = run_dq_checks(workspace_id)
        dq = dq[dq["issues"] > 0]
        story.append(KeepTogether([Paragraph("Data quality", H2), Paragraph(
            "Automated SQL checks on the raw data. Every issue is handled in the cleaned layer before analysis.", SMALL),
            _table([["Check", "Severity", "Records", "%", "Handling"]] + [
                [Paragraph(r.description, SMALL), r.severity, f"{r.issues:,}", f"{r.issue_pct:.2f}", Paragraph(r.handling, SMALL)]
                for r in dq.itertuples()], [55 * mm, 16 * mm, 16 * mm, 12 * mm, 81 * mm], font=7.2)]))
    story.append(Paragraph("Method, assumptions and limitations", H2))
    for line in [
        "Data: synthetic but realistic operator data generated by a reproducible script (fixed seed); no real customer is represented." if telco else "Data: uploaded by the business; quality is as provided.",
        "Features are extracted with SQL using only information available at each snapshot date, preventing leakage of future information.",
        "Model choice: four candidates including a no-skill baseline; selected on PR-AUC because the outcome is rare.",
        "AI narrative: produced by the Snwolley agent from a curated, de-identified context pack; every figure is checked against the source data and the result is labelled.",
        "Monitoring: input and score drift are measured with the Population Stability Index each time customers are re-scored.",
        "Limitations: business value depends on the stated campaign assumptions; drivers are associations, not causes; a controlled test is required before scaling.",
    ]:
        story.append(Paragraph(line, BULLET, bulletText="•"))

    pdf = out_dir / "insight_report.pdf"

    def _footer(canvas, doc):
        canvas.saveState()
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(colors.HexColor(TEXT_SECONDARY))
        canvas.drawString(15 * mm, 10 * mm, f"{ws['name']} · InsightForge · confidential")
        canvas.drawRightString(195 * mm, 10 * mm, f"Page {doc.page}")
        canvas.restoreState()

    doc = SimpleDocTemplate(str(pdf), pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm, topMargin=14 * mm,
                            bottomMargin=16 * mm, title=title, author=author, subject="InsightForge insight report",
                            creator="InsightForge")
    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    audit("report.generated", workspace_id, user_id, run_id=run_id, seconds=round(time.time() - t0, 1))
    log.info("report generated workspace_id=%s run_id=%s", workspace_id, run_id)
    return pdf
