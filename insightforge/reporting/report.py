_ss = getSampleStyleSheet()
H1 = ParagraphStyle("H1", parent=_ss["Title"], fontSize=19, leading=23, alignment=TA_LEFT, textColor=TEXT_PRIMARY, spaceAfter=2)
SUB = ParagraphStyle("SUB", parent=_ss["Normal"], fontSize=9, textColor=TEXT_SECONDARY, spaceAfter=10)
