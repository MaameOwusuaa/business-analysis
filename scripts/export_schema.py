"""Export the DDL (tables + silver views) for MySQL and SQLite into schema/."""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from sqlalchemy.dialects import mysql, sqlite  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

from insightforge.config import SQL_DIR  # noqa: E402
from insightforge.schema import metadata  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]


def ddl(dialect) -> str:
    parts = []
    for table in metadata.sorted_tables:
        parts.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ";")
        for idx in table.indexes:
            parts.append(str(CreateIndex(idx).compile(dialect=dialect)).strip() + ";")
    views = (SQL_DIR / "views.sql").read_text().replace("\n;;", ";")
    return "\n\n".join(parts) + "\n\n" + views


def main() -> None:
    out = ROOT / "schema"
    out.mkdir(exist_ok=True)
    header = "-- InsightForge schema (generated by scripts/export_schema.py from insightforge/schema.py)\n\n"
    (out / "schema_mysql.sql").write_text(header + ddl(mysql.dialect()))
    (out / "schema_sqlite.sql").write_text(header + ddl(sqlite.dialect()))
    print("wrote", out / "schema_mysql.sql", "and", out / "schema_sqlite.sql")


if __name__ == "__main__":
    main()
